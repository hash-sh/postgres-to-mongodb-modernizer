"""Deterministic scaffolding + Mongoose model codegen from design/schema.json.

Why the models are generated, not written by the LLM: they are a mechanical translation of the
already-reviewed schema. Keeping them out of the agent's hands also means the agent can't
"fix" a failing test by quietly changing the schema - a schema problem has to go back to Stage 3.

apps/mongo-backend/ = a copy of the original backend with:
  - models/      regenerated as Mongoose models (pipeline-owned, NOT agent-writable)
  - db/          connection + auto-increment counters (pipeline-owned)
  - package.json sequelize/pg replaced by mongoose (pipeline-owned)
  - everything else copied verbatim; controllers/helpers/middleware/index.js are then rewritten by the agent
"""
import json
import shutil
import subprocess

from pipeline.config import settings

APP = settings.mongo_backend
MODEL_NAME = {"users": "User", "articles": "Article", "comments": "Comment", "tags": "Tag",
              "favorites": "Favorite", "followers": "Follower"}
JS_TYPE = {"int": "Number", "long": "Number", "string": "String", "date": "Date", "bool": "Boolean"}
MONGOOSE_VERSION = "8.19.2"
COPY_SKIP = {"models", "migrations", "seeders", "config", ".sequelizerc", "node_modules", ".env", ".env.example"}


def model_name(coll):
    return MODEL_NAME.get(coll, coll[:1].upper() + coll[1:])


def scaffold(force=False):
    if APP.exists() and not force:
        return False
    if APP.exists():
        shutil.rmtree(APP)
    APP.mkdir(parents=True)
    for p in settings.original_backend.iterdir():
        if p.name in COPY_SKIP or p.name.endswith(".test.js"):
            continue
        (shutil.copytree if p.is_dir() else shutil.copy2)(p, APP / p.name)
    pkg = json.loads((settings.original_backend / "package.json").read_text())
    pkg["name"] = "backend-mongo"
    pkg["description"] = "Conduit backend, data layer modernized from Sequelize/Postgres to Mongoose/MongoDB"
    deps = pkg["dependencies"]
    for d in ("sequelize", "pg", "pg-hstore"):
        deps.pop(d, None)
    deps["mongoose"] = MONGOOSE_VERSION
    pkg.pop("devDependencies", None)
    pkg["scripts"].pop("sqlz", None)
    (APP / "package.json").write_text(json.dumps(pkg, indent=2) + "\n")
    subprocess.run(["npm", "install", "--no-audit", "--no-fund", "--loglevel=error"], cwd=APP, check=True)
    return True


def gen_models(schema):
    (APP / "models").mkdir(exist_ok=True)
    (APP / "db").mkdir(exist_ok=True)
    for f in (APP / "models").glob("*.js"):
        f.unlink()
    (APP / "db/connection.js").write_text('''// GENERATED by pipeline/codegen.py - do not edit.
const mongoose = require("mongoose");

const uri = process.env.MONGO_URI || "mongodb://localhost:27017/?replicaSet=rs0&directConnection=true";
const dbName = process.env.MONGO_DB || "conduit";

async function connect() {
  await mongoose.connect(uri, { dbName });
  // Build the indexes declared in the models (the migrator also creates them for migrated data).
  await Promise.all(Object.values(mongoose.models).map((m) => m.init()));
  return mongoose.connection;
}

module.exports = { mongoose, connect };
''')
    (APP / "db/counters.js").write_text('''// GENERATED by pipeline/codegen.py - do not edit.
// Auto-increment integer ids (users, articles, comments keep integer _ids like the Postgres SERIAL columns;
// comment ids are visible in the API). The migrator sets each counter to the Postgres sequence value.
const { mongoose } = require("./connection");

const Counter = mongoose.models.Counter ||
  mongoose.model("Counter", new mongoose.Schema({ _id: String, seq: Number }, { versionKey: false }), "counters");

async function nextId(name, session) {
  const c = await Counter.findOneAndUpdate({ _id: name }, { $inc: { seq: 1 } },
    { upsert: true, new: true, session });
  return c.seq;
}

module.exports = { nextId, Counter };
''')
    api = []
    names = []
    for c in schema["collections"]:
        name = model_name(c["name"])
        names.append(name)
        lines = ["// GENERATED by pipeline/codegen.py from design/schema.json - do not edit.",
                 f"// Collection `{c['name']}` <- Postgres table `{c['source']}`.",
                 'const { mongoose } = require("../db/connection");', "",
                 f"const {name}Schema = new mongoose.Schema(", "  {"]
        if len(c["id"]) == 1:
            src_type = "String" if c["source"] == "Tags" else "Number"
            lines.append(f"    _id: {{ type: {src_type} }}, // = {c['source']}.{c['id'][0]}")
        else:
            inner = ", ".join(f"{k}: {{ type: Number, required: true }}" for k in c["id"])
            lines.append(f"    _id: {{ {inner} }}, // compound key = {c['source']}({', '.join(c['id'])})")
        for f in c.get("fields", []):
            if f["name"] in ("createdAt", "updatedAt"):
                continue  # managed by timestamps: true, like Sequelize
            default = ", default: null" if f["type"] == "string" else ""
            lines.append(f"    {f['name']}: {{ type: {JS_TYPE[f['type']]}{default} }}, // {c['source']}.{f['from']}")
        for a in c.get("embedArrays", []):
            lines.append(f"    {a['name']}: {{ type: [String], default: [] }}, // embedded {a['fromTable']}.{a['valueColumn']} (max {a['maxItems']})")
        for r in c.get("extendedRefs", []):
            cp = ", ".join(f"{x}: String" for x in r["copy"])
            lines.append(f"    {r['name']}: {{ id: Number, {cp} }}, // extended reference to {r['fromTable']}")
        for k in c.get("counters", []):
            lines.append(f"    {k['name']}: {{ type: Number, default: 0 }}, // = count of {k['fromTable']} by {k['parentKey']}")
        has_ts = any(f["name"] == "createdAt" for f in c.get("fields", []))
        opts = [f'collection: "{c["name"]}"', "versionKey: false"]
        if has_ts:
            opts.append("timestamps: true")
        if len(c["id"]) > 1:
            opts.append("_id: true")
        lines += ["  },", f"  {{ {', '.join(opts)} }},", ");", ""]
        for i in c.get("indexes", []):
            keys = json.dumps(i["keys"]).replace('"', "")
            keys = "{ " + ", ".join(f'"{k}": {v}' for k, v in i["keys"].items()) + " }"
            lines.append(f"{name}Schema.index({keys}{', { unique: true }' if i.get('unique') else ''});")
        lines += ["", f"module.exports = mongoose.models.{name} || mongoose.model(\"{name}\", {name}Schema);", ""]
        (APP / f"models/{name}.js").write_text("\n".join(lines))
        api.append(model_api_line(name, c))
    idx = ["// GENERATED by pipeline/codegen.py - do not edit.", 'const { mongoose, connect } = require("../db/connection");',
           'const { nextId } = require("../db/counters");']
    idx += [f'const {n} = require("./{n}");' for n in names]
    idx += ["", f"module.exports = {{ {', '.join(names)}, mongoose, connect, nextId }};", ""]
    (APP / "models/index.js").write_text("\n".join(idx))
    (settings.root / "design/models_api.txt").write_text("\n".join(api) + "\n")
    return "\n".join(api)


def model_api_line(name, c):
    idd = f"_id:Number(={c['source']}.{c['id'][0]})" if len(c["id"]) == 1 else \
        "_id:{" + ",".join(c["id"]) + "} compound"
    if c["source"] == "Tags":
        idd = "_id:String(=tag name)"
    parts = [idd] + [f"{f['name']}:{f['type']}" for f in c.get("fields", [])]
    parts += [f"{a['name']}:[String] (embedded {a['fromTable']})" for a in c.get("embedArrays", [])]
    parts += [f"{k['name']}:Number (counter of {k['fromTable']}.{k['parentKey']}, YOU must $inc/$dec it)" for k in c.get("counters", [])]
    ix = "; ".join(json.dumps(i["keys"]) for i in c.get("indexes", []))
    return f"- {name} (collection {c['name']}): {', '.join(parts)}. Indexes: {ix or '-'}"
